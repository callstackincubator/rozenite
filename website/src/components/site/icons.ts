/** One SVG path of unit squares for a bitmap. */
export const bitmapPath = (rows: readonly string[]) =>
  rows
    .flatMap((row, y) => [...row].map((c, x) => (c === '#' ? `M${x} ${y}h1v1h-1z` : '')))
    .join('');
